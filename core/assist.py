"""
Режим общей помощи.

Вызывается, когда в базе знаний нет подходящей статьи. Умная модель даёт общую
рекомендацию, но она:
  * помечается как совет ИИ-ассистента, а не инструкция из базы (source == "general");
  * не засчитывается в метрику «решено ботом»;
  * проходит проверку на опасные советы;
  * НЕ обещает пользователю, что обращение кому-то передано. Специалиста зовёт
    система на следующем уровне каскада, и только если эти шаги не помогли.

Это второй уровень каскада: дешёвая модель классифицирует всегда, дорогая
подключается только на промахах. Так дешевле и так честнее.
"""
from __future__ import annotations

import logging
import os
import re

from common.models import AnswerResult
from core import demo_cache
from llm.client import chat

log = logging.getLogger(__name__)

MODEL_SMART = os.getenv("LLM_MODEL_SMART")

SYSTEM = """Ты — инженер технической поддержки крупной компании.
В базе знаний нет готовой инструкции для этого обращения, поэтому дай общую
рекомендацию, которая точно не навредит.

ЖЁСТКИЕ ПРАВИЛА:
1. Только безопасные обратимые действия: перезапуск программы, проверка кабеля
   и питания, проверка интернета, повторный вход, перезагрузка устройства.
2. ЗАПРЕЩЕНО советовать: удаление файлов и папок, форматирование, отключение
   антивируса или защиты, правку реестра, сброс к заводским настройкам,
   переустановку системы, ввод пароля куда-либо.
3. НЕ выдумывай внутренние системы, адреса порталов, названия отделов и телефоны:
   ты не знаешь устройство этой компании.
4. Не более четырёх шагов. Каждый шаг — одно конкретное действие.
5. Ответ на русском. Сначала одна короткая фраза о том, что готовой инструкции
   в базе знаний нет и вы предлагаете общие шаги, затем сами шаги.
6. КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО обещать, что обращение передано специалисту, эксперту
   или оператору, что с пользователем свяжутся или что заявка зарегистрирована.
   Ты этого не решаешь — решает система, и только если твои шаги не помогут.
   Обещание, которого никто не выполнит, хуже, чем отсутствие ответа.
7. Если пользователю уже показали шаги и они не помогли, повторять их
   ЗАПРЕЩЕНО — ни теми же словами, ни другими. Предлагай только то, чего
   он ещё не делал. Если добавить нечего, верни НЕЧЕГО ДОБАВИТЬ и ни одного шага.

Формат ответа — строго такой:
ВСТУПЛЕНИЕ: <одна фраза>
ШАГ: <действие>
ШАГ: <действие>
"""

# Обещание, которого система не давала: одной просьбы в промпте мало, модель
# всё равно иногда пишет «обращение передано специалисту». Такое вступление
# заменяем целиком, иначе пользователь ждёт человека, которого не вызывали.
FALSE_PROMISE = re.compile(
    r"(?i)(специалист|эксперт|оператор|инженер|техподдержк|поддержк\w*\s+свяж"
    r"|свяжут|свяжемся|передан|перенаправ|зарегистрирован|заявк\w*\s+созд)"
)

SAFE_INTRO = "Готовой инструкции для этого случая в базе знаний нет. Попробуем общие шаги — они безопасны."

# Страховка на случай, если модель всё же посоветует лишнего
DANGEROUS = re.compile(
    r"(?i)(удали|снеси|формат|отключ\w*\s+(антивирус|защит|брандмауэр|firewall)"
    r"|реестр|regedit|сброс\w*\s+(до\s+)?заводск|переустанов\w*\s+(систем|windows)"
    r"|system32|rm\s+-rf|введите\s+пароль)"
)


# Слова, которые есть почти в каждом шаге и потому ничего не различают.
# Без их отсева «перезапустите приложение VPN» и «перезапустите компьютер»
# оказались бы похожими сильнее, чем они есть.
_STOP = {"и", "в", "во", "на", "с", "со", "к", "по", "из", "от", "до", "для",
         "если", "затем", "потом", "проверьте", "попробуйте", "убедитесь",
         "что", "это", "все", "всё", "не", "или", "а", "но", "же", "ли"}

# Разные слова об одном и том же действии. Без этого «закройте приложение
# и запустите заново» и «полностью закройте программу и откройте снова»
# считаются разными шагами, хотя пользователь читает их как один и тот же
# и справедливо злится.
_SYNONYMS = {
    "приложение": "программа", "приложения": "программа", "приложении": "программа",
    "приложением": "программа", "программу": "программа", "программы": "программа",
    "программе": "программа", "программой": "программа", "прогу": "программа",
    "софт": "программа", "клиент": "программа",
    "откройте": "запуск", "открыть": "запуск", "запустите": "запуск",
    "запустить": "запуск", "стартуйте": "запуск", "включите": "запуск",
    "закройте": "закрытие", "закрыть": "закрытие", "завершите": "закрытие",
    "выйдите": "закрытие",
    "заново": "снова", "повторно": "снова", "ещё": "снова", "снова": "снова",
    "перезапустите": "перезапуск", "перезапустить": "перезапуск",
    "перезагрузите": "перезагрузка", "перезагрузить": "перезагрузка",
    "компьютер": "компьютер", "комп": "компьютер", "ноутбук": "компьютер",
    "ноут": "компьютер", "пк": "компьютер",
    "соединение": "подключение", "коннект": "подключение",
    "подключение": "подключение", "подключения": "подключение",
    "интернета": "интернет", "интернете": "интернет",
    "сертификата": "сертификат", "сертификате": "сертификат",
    "устройства": "устройство", "устройстве": "устройство",
}

_DUP_THRESHOLD = 0.6


# Грубое отсечение окончаний. Не морфология, а замена ей: «настройках»
# и «настройки», «профиля» и «профиль» должны считаться одним словом,
# иначе перефразированный шаг не опознаётся как повтор. Тянуть в проект
# полноценный стеммер ради этого — лишняя зависимость за сутки до защиты.
_ENDINGS = ("ами", "ями", "ого", "его", "ому", "ему", "ыми", "ими", "ать", "ить",
            "ах", "ях", "ов", "ев", "ый", "ий", "ой", "ая", "яя", "ое", "ее",
            "ые", "ие", "ом", "ем", "ам", "ям", "ет", "ут", "ют",
            "у", "ю", "а", "я", "ы", "и", "е", "о", "ь")

_MIN_STEM = 4


def _stem(word: str) -> str:
    if len(word) <= _MIN_STEM + 1:
        return word
    for ending in _ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= _MIN_STEM:
            return word[: -len(ending)]
    return word


def _tokens(text: str) -> set[str]:
    words = re.findall(r"[а-яёa-z0-9]+", (text or "").lower())
    out = set()
    for w in words:
        if len(w) <= 2 or w in _STOP:
            continue
        # Сначала словарь синонимов по полной форме, потом обрезка окончания.
        out.add(_SYNONYMS.get(w) or _stem(w))
    return out


def _looks_same(a: str, b: str) -> bool:
    """Два шага говорят об одном и том же.

    Сравниваем по множеству значимых слов: модель переформулирует шаг другими
    словами, но опорные существительные и глаголы остаются теми же.
    """
    ta, tb = _tokens(a), _tokens(b)
    if not ta or not tb:
        return False
    overlap = len(ta & tb) / min(len(ta), len(tb))
    return overlap >= _DUP_THRESHOLD


def _drop_repeats(steps: list[str], already_shown: list[str]) -> list[str]:
    """Выбросить шаги, которые пользователь уже видел и которые не помогли."""
    if not already_shown:
        return steps
    kept = []
    for step in steps:
        if any(_looks_same(step, shown) for shown in already_shown):
            log.info("шаг отброшен как повтор уже показанного: %s", step[:60])
            continue
        kept.append(step)
    return kept


def _sanitize(answer: AnswerResult) -> AnswerResult:
    """Убрать из вступления обещание, которого система не давала."""
    text = (answer.text or "").strip()
    if not text or FALSE_PROMISE.search(text):
        if text:
            log.info("вступление обещало специалиста, заменено нейтральным")
        answer.text = SAFE_INTRO
    return answer


def general_help(user_text: str, category: str,
                 exclude_steps: list[str] | None = None) -> AnswerResult | None:
    """Вернуть общую рекомендацию или None, если модель недоступна либо ответ опасен.

    Ответы кэшируются наравне с остальными вызовами модели: в демонстрационном
    режиме эта ветка тоже обязана работать без сети, иначе страховка на защите
    неполная — а именно здесь она нужнее всего.
    """
    exclude_steps = [s for s in (exclude_steps or []) if isinstance(s, str) and s.strip()]

    # Уже показанные шаги входят в ключ кэша. Иначе ответ, выданный при первом
    # обращении «шагов не было», подставился бы во второе, где они были,
    # и дубли вернулись бы через кэш в обход всех проверок.
    key = demo_cache.key_for("assist", user_text, category,
                             "|".join(exclude_steps)[:500])
    hit = demo_cache.get(key)
    if hit is not None:
        # Ответы из кэша тоже чистим: он мог быть прогрет старой версией промпта.
        cached = _sanitize(AnswerResult(**hit))
        cached.steps = _drop_repeats(cached.steps, exclude_steps)
        return cached if cached.steps else None

    if demo_cache.demo_mode():
        log.info("демо-режим: общей рекомендации нет в кэше, передаём специалисту")
        return None

    user_parts = [f"Категория (предположительно): {category}",
                  f"Обращение: {user_text}"]
    if exclude_steps:
        shown = "\n".join(f"- {s}" for s in exclude_steps)
        user_parts.append(
            "Пользователю УЖЕ показали эти шаги, и они не помогли. "
            "Повторять их нельзя, предлагай только новое:\n" + shown)

    raw = chat(
        [{"role": "system", "content": SYSTEM},
         {"role": "user", "content": "\n".join(user_parts)}],
        model=MODEL_SMART, temperature=0.3, max_tokens=500,
    )
    if not raw:
        return None

    if DANGEROUS.search(raw):
        log.warning("общая рекомендация отклонена фильтром безопасности")
        return None

    intro, steps = "", []
    for line in raw.splitlines():
        line = line.strip()
        if line.upper().startswith("ВСТУПЛЕНИЕ:"):
            intro = line.split(":", 1)[1].strip()
        elif line.upper().startswith("ШАГ:"):
            steps.append(line.split(":", 1)[1].strip())

    if not steps:
        return None

    # Постфильтр поверх правила в промпте: правилам модель следует не всегда,
    # а повтор уже провалившихся шагов пользователь читает как «меня не слушают».
    steps = _drop_repeats(steps, exclude_steps)
    if not steps:
        log.info("все предложенные шаги повторяли уже показанные — зовём человека")
        return None

    result = _sanitize(AnswerResult(text=intro, steps=steps[:4]))
    demo_cache.put(key, result.model_dump())
    return result
