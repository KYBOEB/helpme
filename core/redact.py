"""
Маскирование чувствительных данных перед отправкой во внешнюю модель.
ВЛАДЕЛЕЦ: A.

Зачем: в обращение пользователь может вписать почту, телефон, доменный логин
и даже пароль. В базе обращений мы храним оригинал — он нужен специалисту, —
а во внешнюю модель уходит уже очищенный текст.

Честная граница: регулярные выражения не распознают ФИО и не дают стопроцентной
гарантии. Это снижение риска, а не его устранение. Полностью задача решается
моделью, развёрнутой в контуре заказчика, и архитектура это позволяет —
провайдер меняется одной переменной LLM_BASE_URL.
"""
from __future__ import annotations

import re

# Порядок важен: сначала то, что содержит цифры и символы других шаблонов.
_RULES: list[tuple[str, re.Pattern]] = [
    # пароль/пин, названные явно: «пароль qwerty123», «password: 1234»
    ("SECRET", re.compile(
        r"(?i)\b(?:парол\w*|пин[- ]?код\w*|password|passwd|pwd|pin|секрет\w*|токен)\b"
        r"\s*[:=—-]?\s*([^\s,;]{3,}?)(?=[\s,;]|$)")),
    # ключи и токены вида sk-..., длинные бессмысленные строки
    ("SECRET", re.compile(r"\b(?:sk|pk|api)[-_][A-Za-z0-9_\-]{16,}\b")),
    ("EMAIL", re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.-]{2,}\b")),
    # доменный логин CORP\ivanov
    ("LOGIN", re.compile(r"\b[A-Za-z][A-Za-z0-9_-]{1,20}\\[A-Za-z][A-Za-z0-9._-]{1,30}\b")),
    ("IP", re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b")),
    # банковская карта: 13–19 цифр, возможно через пробелы или дефисы
    ("CARD", re.compile(r"\b(?:\d[ -]?){13,19}\b")),
    # телефон в российских форматах
    ("PHONE", re.compile(
        r"(?:\+7|\b8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}\b")),
    # длинные номера: счета, инвентарные, СНИЛС и подобное
    ("NUMBER", re.compile(r"\b\d{10,}\b")),
]


def redact(text: str) -> tuple[str, dict[str, int]]:
    """Вернуть очищенный текст и счётчик срабатываний по типам.

    Счётчик пишем в журнал вместо самого текста: так видно, что фильтр работает,
    но содержимое обращения в логи не попадает.
    """
    if not text:
        return text, {}

    found: dict[str, int] = {}
    clean = text

    for label, pattern in _RULES:
        placeholder = f"<{label}>"

        def _sub(m: re.Match) -> str:
            found[label] = found.get(label, 0) + 1
            # у правила про пароль маскируем только само значение, а не слово
            if m.groups():
                return m.group(0).replace(m.group(1), placeholder)
            return placeholder

        clean = pattern.sub(_sub, clean)

    return clean, found
